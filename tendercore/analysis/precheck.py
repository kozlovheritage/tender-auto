def check_title(subject: str) -> Optional[str]:
    """Возвращает причину отказа по названию или None. (100% parity с монолитом)"""
    if not subject:
        return None
        
    subject_str = str(subject)
    subject_lower = subject_str.lower()
    subject_upper = subject_str.upper()

    # Подшипники
    if re.search(r'подшипник', subject_lower):
        return "подшипники в предмете закупки"

    # Запорная арматура, задвижки, затворы (стоп-фактор №8)
    if re.search(r'запорн\w*\s+арматур', subject_lower):
        return "запорная арматура в предмете закупки"
    if re.search(r'\bзадвижк', subject_lower):
        return "задвижки в предмете закупки"
    if re.search(r'\bзатвор\w*\b', subject_lower):
        return "затворы в предмете закупки"

    # Моторные масла
    if re.search(r'(моторн\w+\s+масл|масл\w+\s+моторн)', subject_lower):
        return "моторные масла в предмете закупки"

    # GPS / навигация
    if re.search(r'\b(gps|глонасс|навигатор\b)', subject_lower, re.IGNORECASE):
        return "GPS/навигация в предмете закупки"

    # Аренда / прокат (стоп-фактор #11)
    if re.search(r'\bаренд|\bпрокат\s+оборудования|\bпрокат\s+техник', subject_lower):
        return "аренда/прокат в предмете закупки (не поставка товара)"

    # Работы / услуги (стоп-фактор #11)
    if re.search(
        r'ремонтн\w*\s+работ|монтажн\w*\s+работ|строительн\w*\s+работ'
        r'|пусконаладочн|техническ\w*\s+обслуживани'
        r'|\bвыполнени\w*\s+работ|\bоказани\w*\s+услуг',
        subject_lower
    ):
        return "работы/услуги в предмете закупки (не поставка товара)"

    # ИСАС — только российское производство (стоп-фактор #3)
    if re.search(
        r'\bисас\b|интеллектуальн\w+\s+систем\w+\s+учёт\w+\s+электроэнерги'
        r'|интеллектуальн\w+\s+систем\w+\s+учета\s+электроэнерги',
        subject_lower
    ):
        return "ИСАС (интеллектуальная система учёта электроэнергии) — только российское производство (стоп-фактор #3)"

    # Российские бренды (транспорт, тракторы, двигатели)
    for abbr in RUSSIAN_BRAND_ABBREVIATIONS:
        pattern = r'\b' + re.escape(abbr.upper()) + r'\b'
        if re.search(pattern, subject_upper):
            return f"российская марка '{abbr}' в предмете закупки"

    # Российские IT-бренды (стоп-фактор #12)
    m_it = RUSSIAN_IT_BRANDS_RE.search(subject_str)
    if m_it:
        return (f"российский IT-бренд '{m_it.group(0)}' в предмете закупки — "
                f"российский производитель выиграет тендер (стоп-фактор #12)")

    # ── Стоп-фактор #14: бытовые / потребительские товары ──────────────────
    for pat in CONSUMER_GOODS:
        if re.search(pat, subject_lower):
            matched = re.search(pat, subject_lower).group()
            return f"бытовые/потребительские товары в предмете закупки ({matched})"

    for pat in CONSUMER_GOODS_EXTRA:
        if re.search(pat, subject_lower):
            matched = re.search(pat, subject_lower).group()
            return f"бытовые/потребительские товары в предмете закупки ({matched})"

    # Молоток
    if re.search(r'\bмолото[кч]\w*\b|\bмолотки\b', subject_lower) and not _HAMMER_TECH.search(subject_str):
        return "бытовые/потребительские товары в предмете закупки (молоток)"

    # ── Стоп-фактор #15а: строительные материалы ─────────────────────────
    for pat in BUILDING_MATERIALS:
        if re.search(pat, subject_lower):
            matched = re.search(pat, subject_lower).group()
            return f"строительные материалы российского производства ({matched}) — стоп-фактор #15"

    # ── Стоп-фактор #15б: металлопрокат ──────────────────────────────────
    if not METAL_EXCLUDE.search(subject_str):
        for pat in METAL_ROLL:
            if re.search(pat, subject_lower):
                matched = re.search(pat, subject_lower).group()
                return f"металлопрокат российского производства ({matched}) — стоп-фактор #15"

    # ── Стоп-фактор #15в: трубы ──────────────────────────────────────────
    if not PIPE_EXCLUDE.search(subject_str):
        for pat in PIPE_PATTERNS:
            if re.search(pat, subject_lower):
                matched = re.search(pat, subject_lower).group()
                return f"трубопроводная продукция российского производства ({matched}) — стоп-фактор #15"

    # ── Стоп-фактор #15г: противопожарное оборудование МЧС РФ ───────────
    for pat in FIRE_SAFETY:
        if re.search(pat, subject_lower):
            matched = re.search(pat, subject_lower).group()
            return f"противопожарное оборудование МЧС РФ ({matched}) — стоп-фактор #15"

    # ── Стоп-фактор #15д: котлы российских серий ─────────────────────────
    if RUSSIAN_BOILERS.search(subject_str):
        m = RUSSIAN_BOILERS.search(subject_str).group().strip()
        return f"котёл российской серии ({m}) — производится преимущественно в РФ (стоп-фактор #15)"

    # ── Стоп-фактор #16: артикул по российской КД ────────────────────────
    if RKDS_ARTICLE.search(subject_str):
        return "артикул по российской конструкторской документации в предмете закупки (стоп-фактор #16)"

    # ── Стоп-фактор #15: кабель ──────────────────────────────────────────
    if RUSSIAN_CABLE_MARKS.search(subject_str):
        m = RUSSIAN_CABLE_MARKS.search(subject_str).group().strip()
        return f"кабель российской марки ({m}) — производится преимущественно в РФ (стоп-фактор #15)"
        
    # ── Стоп-фактор #19: компьютерные комплектующие / ЦОД ────────────────
    if re.search(
        r'\b(материнск\w*\s+плат\w*|процессор\w*|оперативн\w*\s+памят\w*|'
        r'патч[-\s]?панел\w*|патч[-\s]?корд\w*|серверн\w*\s+(?:стойк|шкаф|корпус)\w*|'
        r'центр\w*\s+обработк\w*\s+данных|ЦОД\b|дата[-\s]?центр\w*)',
        subject_lower
    ):
        return "компьютерные комплектующие/оборудование ЦОД (стоп-фактор #19)"

    return None